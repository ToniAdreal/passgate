"""Typed tool surface the agent is allowed to use. Nothing else is exposed."""
from __future__ import annotations

from typing import Protocol


class AirwallexError(RuntimeError):
    def __init__(self, status: int, code: str, message: str = ""):
        super().__init__(f"{status} {code}: {message}")
        self.status, self.code, self.message = status, code, message


class IssuingClient(Protocol):
    name: str

    def get_balance(self, currency: str) -> float: ...
    def create_cardholder(self, email: str, request_id: str) -> dict: ...
    def get_cardholder(self, cardholder_id: str) -> dict: ...
    def create_card(self, payload: dict) -> dict: ...
    def get_card(self, card_id: str) -> dict: ...
    def get_card_limits(self, card_id: str) -> dict: ...
    def update_card_controls(self, card_id: str, controls: dict, request_id: str) -> dict: ...
    def set_card_status(self, card_id: str, status: str, request_id: str) -> dict: ...  # ACTIVE|INACTIVE|CLOSED
    # sandbox simulation
    def sim_authorize(self, card_id: str, amount: float, currency: str, mcc: str, merchant: str) -> dict: ...
    def sim_capture(self, lifecycle_id: str) -> dict: ...
    def list_transactions(self, card_id: str) -> list[dict]: ...
